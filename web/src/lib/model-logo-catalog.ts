export function createModelLogoOption(item: { id: string; title: string; fullTitle?: string }) {
    const categories = [...(categoriesById.get(item.id.toLowerCase()) ?? [])];
    const label = labels[item.id] || item.title;
    const title = item.fullTitle || item.title;
    return {
        id: item.id,
        label,
        title,
        categories,
        searchText: `${item.id} ${label} ${title} ${aliases[item.id] || ""}`.toLowerCase(),
    };
}

// 库升级时由专项测试检查：新增 ID 必须明确分类，删除或改名的 ID 必须清理本地配置。
export function getModelLogoCatalogIssues(items: ReadonlyArray<{ id: string }>) {
    const availableIds = new Set(items.map((item) => item.id));
    const referencedIds = new Set([...Object.values(categoryIds).flat(), ...Object.values(MODEL_LOGO_FEATURED).flat(), ...Object.keys(labels), ...Object.keys(aliases)]);
    return {
        unclassifiedIds: items
            .filter((item) => !categoriesById.has(item.id.toLowerCase()))
            .map((item) => item.id)
            .sort(),
        staleIds: [...referencedIds].filter((id) => !availableIds.has(id)).sort(),
    };
}
